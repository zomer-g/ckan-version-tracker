/* Service worker for over.org.il — makes the site installable and keeps the
   shell usable on a flaky connection. Hand-written rather than generated by
   vite-plugin-pwa: the strategy is four rules, and the one thing a generated
   precache list would add (every hashed chunk up front) is the wrong trade for
   a site with dozens of lazy route chunks most visitors never open.

   What it touches, and why:
   - /assets/*  cache-first. Vite hashes every name, so a URL's bytes never
     change (main.py serves them `immutable` for the same reason). Cached on
     first use. Keeping old chunks also helps a tab opened before a deploy:
     lazyPage.ts reloads on a missing chunk, but one already cached never goes
     missing.
   - Google Fonts  stale-while-revalidate for the CSS, cache-first for the
     font files (gstatic URLs are versioned).
   - top-level icons  stale-while-revalidate.
   - page navigations  network-first, so a deploy shows up on the next load
     exactly as without a worker; only when the network fails do we answer,
     with the offline page.
   Everything else — /api/* above all, whose answers are live data, auth, or a
   302 to R2 — is never intercepted: no respondWith, the browser fetches it as
   if no worker existed. Same for non-GET requests and any other origin.

   Bump VERSION when the strategy or the offline page changes; activate drops
   every cache that does not carry the current one. */

const VERSION = "v1";
const PREFIX = "over-";
const SHELL = `${PREFIX}shell-${VERSION}`;
const ASSETS = `${PREFIX}assets-${VERSION}`;
const FONTS = `${PREFIX}fonts-${VERSION}`;

const OFFLINE_URL = "/offline.html";
const ICONS = new Set([
  "/favicon.svg",
  "/icon-192.png",
  "/icon-512.png",
  "/icon-maskable-512.png",
  "/apple-touch-icon.png",
]);
const FONT_HOSTS = new Set(["fonts.googleapis.com", "fonts.gstatic.com"]);

// Each deploy adds a new set of hashed chunks under new names and nothing
// removes the old ones. Past this many entries the oldest go first (cache
// keys come back in insertion order).
const MAX_ASSETS = 300;

// Server routes that share the origin with the SPA but are not pages of it:
// the API, the MCP endpoints (/mcp, /data/mcp, /nadlan/mcp, … with their OAuth
// screens) and .well-known. A navigation to one of these must reach the
// server untouched — not even an offline page in its place.
const BYPASS = /^\/(api\/|\.well-known\/)|(^|\/)mcp(\/|$)/;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(SHELL)
      .then((c) => c.addAll([OFFLINE_URL, ...ICONS]))
      // Take over at once instead of waiting for every tab to close. Safe
      // here because navigations are network-first and assets are immutable
      // by name: an old page and a new worker never disagree about a file.
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  const keep = new Set([SHELL, ASSETS, FONTS]);
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith(PREFIX) && !keep.has(k))
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);

  if (url.origin !== self.location.origin) {
    if (FONT_HOSTS.has(url.hostname)) {
      event.respondWith(
        url.hostname === "fonts.gstatic.com"
          ? cacheFirst(req, FONTS)
          : staleWhileRevalidate(event, FONTS),
      );
    }
    return;
  }

  if (BYPASS.test(url.pathname)) return;

  if (req.mode === "navigate") {
    event.respondWith(networkFirstPage(req));
    return;
  }
  if (url.pathname.startsWith("/assets/")) {
    event.respondWith(cacheFirst(req, ASSETS, MAX_ASSETS));
    return;
  }
  if (ICONS.has(url.pathname)) {
    event.respondWith(staleWhileRevalidate(event, SHELL));
  }
});

// Worth keeping: a real answer, not an error and not the SPA's HTML fallback
// (a missing /assets file would otherwise be cached as index.html under a
// .js name forever). Opaque is allowed for the cross-origin Google Fonts
// stylesheet, which the page requests without CORS.
function cacheable(res) {
  if (res.type === "opaque") return true;
  if (!res.ok) return false;
  const type = res.headers.get("content-type") || "";
  return !type.startsWith("text/html");
}

async function cacheFirst(req, cacheName, maxEntries) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (cacheable(res)) {
    await cache.put(req, res.clone());
    if (maxEntries) await trim(cache, maxEntries);
  }
  return res;
}

async function staleWhileRevalidate(event, cacheName) {
  const req = event.request;
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  const fresh = fetch(req)
    .then(async (res) => {
      if (cacheable(res)) await cache.put(req, res.clone());
      return res;
    })
    .catch(() => undefined);
  // The refresh outlives the response when a cached copy answered first.
  event.waitUntil(fresh);
  return hit || (await fresh) || Response.error();
}

async function networkFirstPage(req) {
  try {
    return await fetch(req);
  } catch {
    const offline = await caches.match(OFFLINE_URL);
    return offline || Response.error();
  }
}

async function trim(cache, maxEntries) {
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - maxEntries; i++) await cache.delete(keys[i]);
}
